ROTATE_HEALTH_TIMEOUT = 300.0

# Credential stores whose live state must change with the file. Users match templates/<service>.json
# (POSTGRES_USER, RABBITMQ_DEFAULT_USER); test_secrets checks that they agree.
POSTGRES_SERVICE, POSTGRES_USER, POSTGRES_VOLUME = "postgres", "postgres", "postgres_data"
RABBITMQ_SERVICE, RABBITMQ_USER, RABBITMQ_VOLUME = "rabbitmq", "grdm", "rabbitmq_data"

# Shell snippets run inside the container with `sh -c <script> sh <user>`; secrets arrive on stdin.
PG_SET_PASSWORD = (
    'read -r old; read -r new; export PGPASSWORD="$old"; '
    'printf "ALTER USER \\"%s\\" WITH PASSWORD \'%s\';\\n" "$1" "$new" '
    '| psql -v ON_ERROR_STOP=1 -q -h 127.0.0.1 -U "$1" -d postgres >/dev/null'
)
PG_CHECK_PASSWORD = 'read -r pw; PGPASSWORD="$pw" psql -q -h 127.0.0.1 -U "$1" -d postgres -c "SELECT 1" >/dev/null 2>&1'
RMQ_SET_PASSWORD = 'read -r pw; rabbitmqctl -q change_password "$1" "$pw" >/dev/null'
RMQ_CHECK_PASSWORD = 'read -r pw; rabbitmqctl -q authenticate_user "$1" "$pw" >/dev/null 2>&1'


def default_runner(argv: list[str], input: str | None = None) -> tuple[int, str]:  # noqa: A002 - mirrors subprocess
    """Run argv with optional stdin text; stdout is returned, stderr discarded (it may echo SQL)."""
    try:
        proc = subprocess.run(argv, input=input, capture_output=True, text=True)
    except OSError as exc:
        return 127, str(exc)
    return proc.returncode, proc.stdout


def env_path(ctx: Context) -> Path:
    return ctx.runtime / ".env"


def port_key(service: str) -> str:
    return f"GRDM_PORT_{service.upper()}"


def generate_secret(key: str) -> str:
    return _secrets.token_urlsafe(_SECRET_BYTES.get(key, _DEFAULT_BYTES))


def read_env(path: Path) -> dict[str, str]:
    """Parse KEY=value lines (comments and blanks ignored; surrounding quotes stripped)."""
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        key = key.strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        if key:
            values[key] = value
    return values


def write_env(path: Path, values: dict[str, str]) -> None:
    """Write the file atomically with mode 0600 inside a 0700 directory."""
    path.parent.mkdir(parents=True, exist_ok=True)
    os.chmod(path.parent, 0o700)  # nosemgrep: python.lang.security.audit.insecure-file-permissions.insecure-file-permissions -- owner-only (0700) is the intended restriction
    body = HEADER + "".join(f"{k}={v}\n" for k, v in values.items())
    tmp = path.with_name(path.name + ".tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write(body)
    os.chmod(tmp, 0o600)
    os.replace(tmp, path)
    os.chmod(path, 0o600)


def fresh_secrets() -> dict[str, str]:
    return {key: generate_secret(key) for key in SECRET_KEYS}


def default_non_secrets(profile: str) -> dict[str, str]:
    values = {"GRDM_PROFILE": profile}
    for service, port in DEFAULT_PORTS.items():
        values[port_key(service)] = str(port)
    return values


def _cas_key_usable(key: str, value: str) -> bool:
    low, high = CAS_KEY_RULES[key]
    size = len(value.encode("utf-8"))
    if size < low or (high is not None and size > high):
        return False
    if not CAS_KEY_ALPHABET.fullmatch(value):
        return False
    if value.lower() in FORBIDDEN_DEFAULTS:
        return False
    if hashlib.sha256(value.encode("utf-8")).hexdigest() in PUBLISHED_CAS_KEY_DIGESTS:
        return False
    if key in CAS_DECODED_BYTES:
        raw = base64.urlsafe_b64decode(value + "=" * (-len(value) % 4))
        # a non-canonical final character decodes too, but to bits CAS would not use as written
        if len(raw) != CAS_DECODED_BYTES[key] or base64.urlsafe_b64encode(raw).decode("ascii").rstrip("=") != value:
            return False
    return True


def cas_key_problems(values: dict[str, str]) -> list[str]:
    """CAS keys that are present but unusable: wrong length, outside the base64url alphabet (whitespace, quotes),
    a forbidden or published default, or (TGC encryption) not canonical base64url of 32 bytes. Names only, never values."""
    return [key for key in CAS_KEY_RULES if key in values and not _cas_key_usable(key, values[key])]


def check_no_defaults(values: dict[str, str]) -> list[str]:
    """Return secret keys whose value is a forbidden upstream default, too short, or a length CAS cannot use."""
    bad = cas_key_problems(values)
    for key in SECRET_KEYS:
        v = values.get(key, "")
        if v.lower() in FORBIDDEN_DEFAULTS or len(v) < 32:
            bad.append(key)
    if len(values.get("DJANGO_SECRET_KEY", "")) < 50:
        bad.append("DJANGO_SECRET_KEY")
    return sorted(set(bad))


def file_mode(path: Path) -> int:
    return stat.S_IMODE(path.stat().st_mode)


def register(subparsers) -> None:
    p = subparsers.add_parser("secrets", help="init: write random secrets to runtime/.env (0600); rotate: regenerate them")
    p.set_defaults(_module=sys.modules[__name__], secrets_action=None)
    sub = p.add_subparsers(dest="secrets_action", metavar="<action>")
    init = sub.add_parser("init", help="create runtime/.env with random secrets; refuses to overwrite without --force")
    init.add_argument("--force", action="store_true", help="overwrite an existing runtime/.env")
    init.add_argument("--missing", action="store_true",
                      help="upgrade an existing runtime/.env: keep every value, add only the keys it lacks and drop retired ones "
                           "(no database password changes; use `rotate` to replace the existing secrets)")
    init.set_defaults(_module=sys.modules[__name__], secrets_action="init")
    rot = sub.add_parser("rotate", help="regenerate every secret, change the live postgres/rabbitmq passwords, recreate containers; exit 40 on failure (previous .env restored)")
    rot.add_argument("--timeout", type=float, default=ROTATE_HEALTH_TIMEOUT, help=f"seconds to wait for health after recreation (default {int(ROTATE_HEALTH_TIMEOUT)})")
    rot.set_defaults(_module=sys.modules[__name__], secrets_action="rotate")


def run(ctx: Context, args, runner=None, running_services=None, prober=None, sleep=None) -> int:
    action = getattr(args, "secrets_action", None)
    if action == "init":
        return run_init(ctx, force=bool(getattr(args, "force", False)), missing=bool(getattr(args, "missing", False)))
    if action == "rotate":
        return run_rotate(ctx, runner=runner, running_services=running_services, prober=prober, sleep=sleep,
                          timeout=float(getattr(args, "timeout", ROTATE_HEALTH_TIMEOUT)))
    return report.error(ctx, exit_codes.USAGE, "choose `secrets init` or `secrets rotate`")


def _report(ctx: Context, action: str, values: dict[str, str], path: Path, extra: dict | None = None) -> None:
    data = {
        "action": action,
        "path": str(path),
        "mode": oct(file_mode(path)),
        "profile": values.get("GRDM_PROFILE"),
        "secret_keys": [k for k in values if k in SECRET_KEYS],  # names only, never values
        "non_secret_keys": [k for k in values if k not in SECRET_KEYS],
    }
    if extra:
        data.update(extra)
    report.emit(ctx, "secrets", data)


def run_init(ctx: Context, force: bool = False, missing: bool = False) -> int:
    path = env_path(ctx)
    existing = read_env(path) if path.exists() else {}
    if missing and force:
        return report.error(ctx, exit_codes.USAGE, "--missing keeps the existing values and --force replaces them; choose one")
    if missing and existing:
        return _add_missing(ctx, path, existing)
    if path.exists() and not force:
        return report.error(
            ctx, exit_codes.USAGE, f"{path} already exists; keep it (idempotent) or pass --force to overwrite"
        )
    profile = ctx.profile or existing.get("GRDM_PROFILE") or DEFAULT_PROFILE
    values: dict[str, str] = {}
    values.update(default_non_secrets(profile))
    # keep non-secret keys that compose render may have written (remapped ports etc.) when forcing
    for k, v in existing.items():
        if k not in SECRET_KEYS and k not in OBSOLETE_SECRET_KEYS:
            values[k] = v
    if ctx.profile:
        values["GRDM_PROFILE"] = ctx.profile
    values.update(fresh_secrets())
    bad = check_no_defaults(values)
    if bad:  # cannot happen with token_urlsafe, but SPEC-03 §3.1 says fail rather than write a default
        return report.error(ctx, exit_codes.USAGE, "refusing to write default-looking secrets: " + ", ".join(bad))
    write_env(path, values)
    _report(ctx, "init", values, path, {"overwritten": bool(existing)})
    return exit_codes.OK


def _add_missing(ctx: Context, path: Path, existing: dict[str, str]) -> int:
    """`init --missing`: an upgrade that introduces a secret (ELASTIC8_*, ADR-14) must not change the ones the data
    already depends on. Every existing value stays, retired keys go, and only absent keys get a fresh value, so the
    database and broker passwords stay valid and no `rotate` (which needs a healthy running stack) is needed."""
    profile = ctx.profile or existing.get("GRDM_PROFILE") or DEFAULT_PROFILE
    values = {k: v for k, v in existing.items() if k not in OBSOLETE_SECRET_KEYS}
    added: list[str] = []
    for key, value in default_non_secrets(profile).items():
        if key not in values:
            values[key] = value
            added.append(key)
    fresh = fresh_secrets()
    for key in SECRET_KEYS:
        if not values.get(key):
            values[key] = fresh[key]
            added.append(key)
    if ctx.profile:
        values["GRDM_PROFILE"] = ctx.profile
    bad = check_no_defaults(values)
    if bad:
        return report.error(ctx, exit_codes.USAGE, "refusing to keep default-looking secrets: " + ", ".join(bad) + "; run `secrets rotate`")
    dropped = sorted(k for k in existing if k in OBSOLETE_SECRET_KEYS)
    write_env(path, values)
    _report(ctx, "init-missing", values, path, {"added": added, "dropped": dropped})  # names only
    return exit_codes.OK


def _has_data(ctx: Context, volume: str) -> bool:
    d = ctx.runtime / "volumes" / volume
    return d.is_dir() and any(d.iterdir())


def _backup_env(path: Path) -> Path:
    backup = path.with_name(BACKUP_NAME)
    fd = os.open(backup, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "wb") as fh:
        fh.write(path.read_bytes())
    os.chmod(backup, 0o600)
    return backup


def _exec(ctx: Context, runner, service: str, script: str, user: str, stdin: str) -> int:
    from . import health

    rc, _ = runner(health.compose_base(ctx) + ["exec", "-T", service, "sh", "-c", script, "sh", user], input=stdin)
    return rc


def run_rotate(ctx: Context, runner=None, running_services=None, prober=None, sleep=None, timeout: float = ROTATE_HEALTH_TIMEOUT) -> int:
    from . import health, lifecycle  # lazy: lifecycle imports health; avoid import cycles at module load

    runner = runner or default_runner
    path = env_path(ctx)
    if not path.exists():
        return report.error(ctx, exit_codes.USAGE, f"{path} does not exist; run `grdm-dev secrets init` first")
    old_values = read_env(path)
    new_values = {k: v for k, v in old_values.items() if k not in SECRET_KEYS and k not in OBSOLETE_SECRET_KEYS}
    new_values.update(fresh_secrets())

    # 0. what is live? Fail closed before touching anything.
    running: list[str] = []
    if health.compose_path(ctx).exists():
        try:
            running = list(running_services()) if running_services is not None else lifecycle.running_services(ctx, runner=runner)
        except Exception as exc:  # noqa: BLE001 - docker absent or broken
            return report.error(ctx, exit_codes.HEALTH_FAILED,
                                f"secrets rotate: cannot list services ({exc}); start Docker so the live passwords can be changed, or `grdm-dev reset` first")
        for service, volume in ((POSTGRES_SERVICE, POSTGRES_VOLUME), (RABBITMQ_SERVICE, RABBITMQ_VOLUME)):
            if service not in running and _has_data(ctx, volume):
                return report.error(ctx, exit_codes.HEALTH_FAILED,
                                    f"secrets rotate: {service} holds credentials in runtime/volumes/{volume} but is not running; "
                                    f"run `grdm-dev up` first so its password can be changed")

    # 1. backup + write
    backup = _backup_env(path)
    write_env(path, new_values)
    steps: list[dict] = []
    reverts: list[tuple[str, "callable"]] = []
    recreated = False

    def fail(step: str, detail: str) -> int:
        steps.append({"step": step, "status": "failed"})
        for name, revert in reversed(reverts):  # credentials back to the old values
            steps.append({"step": f"revert-{name}", "status": "ok" if revert() == 0 else "failed"})
        shutil.copyfile(backup, path)
        os.chmod(path, 0o600)
        steps.append({"step": "restore-env", "status": "ok"})
        if recreated:
            steps.append({"step": "recreate-with-old-env", "status": "ok" if lifecycle.recreate(ctx, runner=runner) == 0 else "failed"})
        _report(ctx, "rotate", old_values, path, {"result": "rolled-back", "failed_step": step, "steps": steps,
                                                   "live_services": running, "backup": str(backup)})
        return report.error(ctx, exit_codes.HEALTH_FAILED, f"secrets rotate: step `{step}` failed ({detail}); previous runtime/.env restored")

    # 2. postgres
    if POSTGRES_SERVICE in running:
        old_pw, new_pw = old_values.get("POSTGRES_PASSWORD", ""), new_values["POSTGRES_PASSWORD"]
        rc = _exec(ctx, runner, POSTGRES_SERVICE, PG_SET_PASSWORD, POSTGRES_USER, f"{old_pw}\n{new_pw}\n")
        if rc != 0:
            return fail("postgres-alter-password", f"psql exited {rc}")
        reverts.append(("postgres-password", lambda o=old_pw, n=new_pw: _exec(ctx, runner, POSTGRES_SERVICE, PG_SET_PASSWORD, POSTGRES_USER, f"{n}\n{o}\n")))
        steps.append({"step": "postgres-alter-password", "status": "ok"})
        if _exec(ctx, runner, POSTGRES_SERVICE, PG_CHECK_PASSWORD, POSTGRES_USER, f"{old_pw}\n") == 0:
            return fail("postgres-reject-old-password", "the old password is still accepted")
        steps.append({"step": "postgres-reject-old-password", "status": "ok"})
        if _exec(ctx, runner, POSTGRES_SERVICE, PG_CHECK_PASSWORD, POSTGRES_USER, f"{new_pw}\n") != 0:
            return fail("postgres-accept-new-password", "the new password is rejected")
        steps.append({"step": "postgres-accept-new-password", "status": "ok"})

    # 3. rabbitmq
    if RABBITMQ_SERVICE in running:
        old_pw, new_pw = old_values.get("RABBITMQ_DEFAULT_PASS", ""), new_values["RABBITMQ_DEFAULT_PASS"]
        rc = _exec(ctx, runner, RABBITMQ_SERVICE, RMQ_SET_PASSWORD, RABBITMQ_USER, f"{new_pw}\n")
        if rc != 0:
            return fail("rabbitmq-change-password", f"rabbitmqctl exited {rc}")
        reverts.append(("rabbitmq-password", lambda o=old_pw: _exec(ctx, runner, RABBITMQ_SERVICE, RMQ_SET_PASSWORD, RABBITMQ_USER, f"{o}\n")))
        steps.append({"step": "rabbitmq-change-password", "status": "ok"})
        if _exec(ctx, runner, RABBITMQ_SERVICE, RMQ_CHECK_PASSWORD, RABBITMQ_USER, f"{old_pw}\n") == 0:
            return fail("rabbitmq-reject-old-password", "the old password is still accepted")
        steps.append({"step": "rabbitmq-reject-old-password", "status": "ok"})
        if _exec(ctx, runner, RABBITMQ_SERVICE, RMQ_CHECK_PASSWORD, RABBITMQ_USER, f"{new_pw}\n") != 0:
            return fail("rabbitmq-accept-new-password", "the new password is rejected")
        steps.append({"step": "rabbitmq-accept-new-password", "status": "ok"})

    # 4. recreate every container with the new environment, then wait for health
    if running:
        rc = lifecycle.recreate(ctx, runner=runner)
        recreated = True
        if rc != 0:
            return fail("recreate", f"docker compose up --force-recreate exited {rc}")
        steps.append({"step": "recreate", "status": "ok"})
        kwargs = {"runner": runner, "prober": prober or health.default_prober}
        if sleep is not None:
            kwargs["sleep"] = sleep
        rows, ok = health.wait_until_healthy(ctx, timeout, **kwargs)
        if not ok:
            bad = ", ".join(r["service"] for r in rows if not r["ok"]) or "unknown"
            return fail("health-after-recreate", f"not healthy after {int(timeout)}s: {bad}")
        steps.append({"step": "health-after-recreate", "status": "ok"})

    backup.unlink(missing_ok=True)  # it holds the old secrets; nothing may need them now
    _report(ctx, "rotate", new_values, path, {"result": "rotated", "steps": steps, "live_services": running, "recreated": recreated})
    return exit_codes.OK
