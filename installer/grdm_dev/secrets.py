"""grdm-dev secrets init / secrets rotate — random secrets in runtime/.env (SPEC-02 §3, SPEC-03 §3.1).

Key list written to runtime/.env. The service templates under templates/<service>.json reference
these keys as `${KEY}`; `compose render` reads runtime/.env and substitutes the values into the
generated Compose file and the rewritten upstream env files. Add a key here first, then use it in
a template (the test suite checks that every key a template references is generated).

Secret keys (regenerated by `secrets rotate`, never printed, never given a default value):

    POSTGRES_PASSWORD            postgres superuser password (upstream default was postgres/postgres)
    DJANGO_SECRET_KEY            OSF website SECRET_KEY (>= 50 characters)
    API_SECRET_KEY               OSF api SECRET_KEY
    SESSION_COOKIE_SECRET        OSF session cookie signing secret
    RABBITMQ_DEFAULT_PASS        RabbitMQ password for the Celery broker (upstream default was guest)
    WATERBUTLER_JWE_SECRET       waterbutler <-> OSF JWE secret (upstream default was "changeme")
    WATERBUTLER_JWE_SALT         waterbutler <-> OSF JWE salt
    WATERBUTLER_JWT_SECRET       waterbutler <-> OSF JWT secret
    WATERBUTLER_HMAC_SECRET      waterbutler -> OSF callback HMAC secret; both waterbutler signers and OSF DEFAULT_HMAC_SECRET use it
    MFR_SERVER_SECRET            mfr <-> OSF shared secret
    UNOCONV_CONVERT_SECRET       mfr -> unoconv bearer credential for the convert service (ADR-07)
    Y_WEBSOCKET_JWT_SECRET       y-websocket JWT auth secret (adopted PR RDM-osf.io#797)
    ELASTIC8_PASSWORD            Elasticsearch 8 bootstrap superuser `elastic`; only the elasticsearch8 services get it (ADR-14)
    ELASTIC8_OSF_PASSWORD        Elasticsearch 8 user `grdm_osf` that osf.io searches with (role limited to website* indices)
    TGC_ENCRYPTION_KEY           CAS ticket-granting cookie encryption key (43 characters: base64url of 32 bytes)
    TGC_SIGNING_KEY              CAS ticket-granting cookie signing key (86 characters: base64url of 64 bytes)
    OSF_API_INSTITUTIONS_AUTH_JWESECRET  CAS -> osf.io institution login JWE key, osf.io JWE_SECRET (exactly 32 bytes)
    OSF_API_INSTITUTIONS_AUTH_JWTSECRET  CAS -> osf.io institution login JWT key, osf.io JWT_SECRET (at least 32 bytes)

The CAS names are the environment variables the image reads: Spring maps `tgc.encryption.key` to
TGC_ENCRYPTION_KEY, so one name runs from runtime/.env into the container. CAS fails closed on a missing
key and on a JWE or JWT key of the wrong length but does not check the TGC keys itself, so the length, the
alphabet and the decoding of every key (cas_key_problems) are enforced by `secrets init` and `compose render`.

No Sentry key is written: the developer environment reports no errors to an external service.

Former secret keys (OBSOLETE_SECRET_KEYS) are dropped by `init --force`, `init --missing` and `rotate`.
`init --missing` is the upgrade for a runtime/.env that predates a new key (ELASTIC8_*, ADR-14): it keeps every
existing value, adds only the absent keys and changes no live password. Upgrading: a Compose
file rendered before a key was retired still refers to it, so run `grdm-dev compose render` before
`secrets rotate` or any recreate.

Non-secret keys (written by `init` only when absent, kept by `rotate`):

    GRDM_PROFILE                 minimum | core | full (SPEC-02 §5)
    GRDM_PORT_<SERVICE>          default host ports from the SPEC-02 §4 ports table; `compose render`
                                 overwrites a value when it had to remap a busy port

Behavior: the file is created with mode 0600 inside runtime/ (mode 0700). `init` refuses to overwrite
an existing file without --force (exit 2).

`rotate` makes the OLD credentials unusable, not just the file different (SPEC-03 §6 rule 6;
review PR #21 finding 1). Steps, each through the injectable `runner(argv, input=None) -> (rc, out)`:

  0. list the running services (`docker compose ps`); when the compose file exists and the list cannot
     be obtained, or postgres/rabbitmq hold data under runtime/volumes/ but are not running, stop with
     exit 40 before touching anything (a stopped database would keep its old password);
  1. back up runtime/.env to runtime/.env.rotate-backup (0600), write the new values;
  2. postgres: `ALTER USER <user> WITH PASSWORD '<new>'` through `docker compose exec -T postgres sh -c`,
     authenticated over TCP with the OLD password (PGPASSWORD inside the container; old and new values
     travel on stdin, never in argv, so `ps` on the host never shows them), then prove the OLD password is
     rejected and the NEW one accepted;
  3. rabbitmq: `rabbitmqctl change_password <user>` the same way, then `rabbitmqctl authenticate_user`
     must fail with the old and succeed with the new password;
  4. `docker compose up -d --force-recreate` (lifecycle.recreate): every container gets the new
     environment — `restart` alone keeps the old one — then wait for health;
  5. on any failure: revert the credentials already changed (new -> old), restore runtime/.env from the
     backup, recreate again if step 4 had run, and exit 40 naming the failing step. The backup is
     deleted on success so no old secret lingers. Secret values are never printed or reported.
"""
