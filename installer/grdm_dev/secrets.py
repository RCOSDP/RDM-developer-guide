"""grdm-dev secrets init / secrets rotate — random secrets in runtime/.env (SPEC-02 §3, SPEC-03 §3.1).

Key list written to runtime/.env. The service templates under templates/<service>.json reference
these keys as `${KEY}`; `compose render` reads runtime/.env and substitutes the values into the
generated Compose file and the rewritten upstream env files. Add a key here first, then use it in
a template (the test suite checks that every key a template references is generated).

Secret keys (regenerated by `secrets rotate`, never printed, never given a default value):

    POSTGRES_PASSWORD            postgres superuser password (upstream default was postgres/postgres)
    DJANGO_SECRET_KEY            OSF website SECRET_KEY (>= 50 characters)
    API_SECRET_KEY               OSF api SECRET_KEY
    SESSION_COOKIE_SECRET        OSF session cookie signing secret
    RABBITMQ_DEFAULT_PASS        RabbitMQ password for the Celery broker (upstream default was guest)
    WATERBUTLER_JWE_SECRET       waterbutler <-> OSF JWE secret (upstream default was "changeme")
    WATERBUTLER_JWE_SALT         waterbutler <-> OSF JWE salt
    WATERBUTLER_JWT_SECRET       waterbutler <-> OSF JWT secret
    WATERBUTLER_HMAC_SECRET      waterbutler callback HMAC secret
    OSFSTORAGE_HMAC_SECRET       osfstorage provider HMAC secret
    MFR_SERVER_SECRET            mfr <-> OSF shared secret
    SHAREJS_SECRET               sharejs <-> OSF shared secret
    Y_WEBSOCKET_JWT_SECRET       y-websocket JWT auth secret (adopted PR RDM-osf.io#797)
    CAS_TGC_ENCRYPTION_KEY       CAS ticket-granting cookie encryption key
    CAS_TGC_SIGNING_KEY          CAS ticket-granting cookie signing key
    CAS_WEBFLOW_ENCRYPTION_KEY   CAS webflow encryption key
    CAS_WEBFLOW_SIGNING_KEY      CAS webflow signing key

No Sentry key is written: the developer environment reports no errors to an external service.

Non-secret keys (written by `init` only when absent, kept by `rotate`):

    GRDM_PROFILE                 minimum | core | full (SPEC-02 §5)
    GRDM_PORT_<SERVICE>          default host ports from the SPEC-02 §4 ports table; `compose render`
                                 overwrites a value when it had to remap a busy port

Behavior: the file is created with mode 0600 inside runtime/ (mode 0700). `init` refuses to overwrite
an existing file without --force (exit 2). `rotate` keeps non-secret keys, regenerates every secret,
and restarts running services through an injectable callable (default: lifecycle.restart).
"""
from __future__ import annotations

import os
import secrets as _secrets
import stat
import sys
from pathlib import Path

from . import exit_codes, report
from .context import Context

SECRET_KEYS: tuple[str, ...] = (
    "POSTGRES_PASSWORD",
    "DJANGO_SECRET_KEY",
    "API_SECRET_KEY",
    "SESSION_COOKIE_SECRET",
    "RABBITMQ_DEFAULT_PASS",
    "WATERBUTLER_JWE_SECRET",
    "WATERBUTLER_JWE_SALT",
    "WATERBUTLER_JWT_SECRET",
    "WATERBUTLER_HMAC_SECRET",
    "OSFSTORAGE_HMAC_SECRET",
    "MFR_SERVER_SECRET",
    "SHAREJS_SECRET",
    "Y_WEBSOCKET_JWT_SECRET",
    "CAS_TGC_ENCRYPTION_KEY",
    "CAS_TGC_SIGNING_KEY",
    "CAS_WEBFLOW_ENCRYPTION_KEY",
    "CAS_WEBFLOW_SIGNING_KEY",
)

# Bytes of randomness per key; token_urlsafe gives ~1.3 characters per byte. Django wants >= 50 chars.
_SECRET_BYTES: dict[str, int] = {"DJANGO_SECRET_KEY": 48, "API_SECRET_KEY": 48}
_DEFAULT_BYTES = 32

# SPEC-02 §4 ports table: the only place default host ports are defined; copied here as defaults.
DEFAULT_PORTS: dict[str, int] = {
    "web": 5000,
    "api": 8000,
    "admin": 8001,
    "wb": 7777,
    "mfr": 7778,
    "fakecas": 8080,
    "ember_osf_web": 4200,
}

# Values upstream compose files ship with; SPEC-03 §3.1 forbids them anywhere in runtime/.env.
FORBIDDEN_DEFAULTS: frozenset[str] = frozenset({"postgres", "changeme", "guest", "password", "secret", "osf", ""})

DEFAULT_PROFILE = "core"
HEADER = "# generated by grdm-dev secrets init — mode 0600, never commit (SPEC-03 §3.1)\n"


def env_path(ctx: Context) -> Path:
    return ctx.runtime / ".env"


def port_key(service: str) -> str:
    return f"GRDM_PORT_{service.upper()}"


def generate_secret(key: str) -> str:
    return _secrets.token_urlsafe(_SECRET_BYTES.get(key, _DEFAULT_BYTES))


def read_env(path: Path) -> dict[str, str]:
    """Parse KEY=value lines (comments and blanks ignored; surrounding quotes stripped)."""
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        key = key.strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        if key:
            values[key] = value
    return values


def write_env(path: Path, values: dict[str, str]) -> None:
    """Write the file atomically with mode 0600 inside a 0700 directory."""
    path.parent.mkdir(parents=True, exist_ok=True)
    os.chmod(path.parent, 0o700)
    body = HEADER + "".join(f"{k}={v}\n" for k, v in values.items())
    tmp = path.with_name(path.name + ".tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write(body)
    os.chmod(tmp, 0o600)
    os.replace(tmp, path)
    os.chmod(path, 0o600)


def fresh_secrets() -> dict[str, str]:
    return {key: generate_secret(key) for key in SECRET_KEYS}


def default_non_secrets(profile: str) -> dict[str, str]:
    values = {"GRDM_PROFILE": profile}
    for service, port in DEFAULT_PORTS.items():
        values[port_key(service)] = str(port)
    return values


def check_no_defaults(values: dict[str, str]) -> list[str]:
    """Return secret keys whose value is a forbidden upstream default or too short."""
    bad = []
    for key in SECRET_KEYS:
        v = values.get(key, "")
        if v.lower() in FORBIDDEN_DEFAULTS or len(v) < 32:
            bad.append(key)
    if len(values.get("DJANGO_SECRET_KEY", "")) < 50:
        bad.append("DJANGO_SECRET_KEY")
    return sorted(set(bad))


def file_mode(path: Path) -> int:
    return stat.S_IMODE(path.stat().st_mode)


def register(subparsers) -> None:
    p = subparsers.add_parser("secrets", help="init: write random secrets to runtime/.env (0600); rotate: regenerate them")
    p.set_defaults(_module=sys.modules[__name__], secrets_action=None)
    sub = p.add_subparsers(dest="secrets_action", metavar="<action>")
    init = sub.add_parser("init", help="create runtime/.env with random secrets; refuses to overwrite without --force")
    init.add_argument("--force", action="store_true", help="overwrite an existing runtime/.env")
    init.set_defaults(_module=sys.modules[__name__], secrets_action="init")
    rot = sub.add_parser("rotate", help="regenerate every secret, keep non-secret keys, restart running services")
    rot.set_defaults(_module=sys.modules[__name__], secrets_action="rotate")


def run(ctx: Context, args, runner=None, restart=None, running_services=None) -> int:
    action = getattr(args, "secrets_action", None)
    if action == "init":
        return run_init(ctx, force=bool(getattr(args, "force", False)))
    if action == "rotate":
        return run_rotate(ctx, runner=runner, restart=restart, running_services=running_services)
    return report.error(ctx, exit_codes.USAGE, "choose `secrets init` or `secrets rotate`")


def _report(ctx: Context, action: str, values: dict[str, str], path: Path, extra: dict | None = None) -> None:
    data = {
        "action": action,
        "path": str(path),
        "mode": oct(file_mode(path)),
        "profile": values.get("GRDM_PROFILE"),
        "secret_keys": [k for k in values if k in SECRET_KEYS],  # names only, never values
        "non_secret_keys": [k for k in values if k not in SECRET_KEYS],
    }
    if extra:
        data.update(extra)
    report.emit(ctx, "secrets", data)


def run_init(ctx: Context, force: bool = False) -> int:
    path = env_path(ctx)
    existing = read_env(path) if path.exists() else {}
    if path.exists() and not force:
        return report.error(
            ctx, exit_codes.USAGE, f"{path} already exists; keep it (idempotent) or pass --force to overwrite"
        )
    profile = ctx.profile or existing.get("GRDM_PROFILE") or DEFAULT_PROFILE
    values: dict[str, str] = {}
    values.update(default_non_secrets(profile))
    # keep non-secret keys that compose render may have written (remapped ports etc.) when forcing
    for k, v in existing.items():
        if k not in SECRET_KEYS:
            values[k] = v
    if ctx.profile:
        values["GRDM_PROFILE"] = ctx.profile
    values.update(fresh_secrets())
    bad = check_no_defaults(values)
    if bad:  # cannot happen with token_urlsafe, but SPEC-03 §3.1 says fail rather than write a default
        return report.error(ctx, exit_codes.USAGE, "refusing to write default-looking secrets: " + ", ".join(bad))
    write_env(path, values)
    _report(ctx, "init", values, path, {"overwritten": bool(existing)})
    return exit_codes.OK


def run_rotate(ctx: Context, runner=None, restart=None, running_services=None) -> int:
    path = env_path(ctx)
    if not path.exists():
        return report.error(ctx, exit_codes.USAGE, f"{path} does not exist; run `grdm-dev secrets init` first")
    values = read_env(path)
    kept = {k: v for k, v in values.items() if k not in SECRET_KEYS}
    new_values = dict(kept)
    new_values.update(fresh_secrets())
    write_env(path, new_values)

    restarted: list[str] = []
    if running_services is None or restart is None:
        from . import lifecycle  # lazy: lifecycle imports health; avoid import cycles at module load

        running_services = running_services or (lambda: lifecycle.running_services(ctx, runner=runner))
        restart = restart or (lambda services: lifecycle.restart(ctx, services, runner=runner))
    try:
        running = list(running_services())
    except Exception as exc:  # docker absent: rotation still succeeded, just nothing to restart
        sys.stderr.write(f"[grdm-dev] secrets rotate: could not list services ({exc}); nothing restarted\n")
        running = []
    if running:
        rc = restart(running)
        if rc != 0:
            _report(ctx, "rotate", new_values, path, {"restarted": [], "restart_failed": True})
            return report.error(ctx, exit_codes.HEALTH_FAILED, "services could not be restarted after rotation")
        restarted = running
    _report(ctx, "rotate", new_values, path, {"restarted": restarted})
    return exit_codes.OK
